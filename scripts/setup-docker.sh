#!/usr/bin/env bash
# BabyApp local setup — one command from a fresh checkout:
#
#   scripts/setup-docker.sh
#
# What it does:
#   1. Generates docker/supabase/.env (fresh random secrets + matching
#      ANON_KEY / SERVICE_ROLE_KEY) from docker/supabase/.env.example.
#   2. Generates the root .env (client config) and points VITE_SUPABASE_*
#      at the local stack. Existing values are never overwritten.
#   3. Syncs supabase/functions/* into the edge-runtime volume.
#   4. docker compose up -d --build (web + full Supabase stack).
#   5. Waits for db / kong / auth / edge functions / web to be healthy.
#   6. Applies supabase/migrations (idempotent).
#
# Re-runnable: it keeps existing .env files and only fills in what is
# missing. To start from scratch: delete .env, docker/supabase/.env and
# docker/supabase/volumes/db/data, then re-run.
set -euo pipefail
cd "$(dirname "$0")/.."

SBU_ENV=docker/supabase/.env
ROOT_ENV=.env
KONG_HTTP_PORT="${KONG_HTTP_PORT:-8000}"
WEB_PORT="${WEB_PORT:-8088}"

info()  { printf '\n\033[1;34m== %s\033[0m\n' "$*"; }
ok()    { printf '  \033[0;32m✓\033[0m %s\n' "$*"; }
fail()  { printf '  \033[0;31m✗ %s\033[0m\n' "$*" >&2; exit 1; }

# --------------------------------------------------------------------------
# Preflight
# --------------------------------------------------------------------------
command -v docker >/dev/null || fail "docker is not installed"
docker compose version >/dev/null 2>&1 || fail "docker compose v2 is not available"
command -v node >/dev/null || fail "node is required (used to generate the API keys)"
docker info >/dev/null 2>&1 || fail "cannot reach the docker daemon — start Docker and re-run"

# --------------------------------------------------------------------------
# 1. docker/supabase/.env
# --------------------------------------------------------------------------
if [ -f "$SBU_ENV" ]; then
  info "docker/supabase/.env already exists — keeping it"
else
  info "generating docker/supabase/.env with fresh secrets"
  # Random values come from node (already a hard requirement of the repo).
  rand_hex() {
    node -e 'process.stdout.write(require("node:crypto").randomBytes(+process.argv[1]).toString("hex"))' "$1"
  }
  rand_b64() { # bytes max-length
    node -e '
      const s = require("node:crypto").randomBytes(+process.argv[1])
        .toString("base64").replace(/[+/=]/g, "");
      process.stdout.write(s.slice(0, +process.argv[2]));
    ' "$1" "$2"
  }

  # Honour values explicitly exported by the user; otherwise randomize.
  POSTGRES_PASSWORD="${POSTGRES_PASSWORD:-$(rand_hex 24)}"
  JWT_SECRET="${JWT_SECRET:-$(rand_hex 24)}"
  SECRET_KEY_BASE="${SECRET_KEY_BASE:-$(rand_hex 48)}"
  VAULT_ENC_KEY="${VAULT_ENC_KEY:-$(rand_hex 16)}"
  PG_META_CRYPTO_KEY="${PG_META_CRYPTO_KEY:-$(rand_b64 48 64)}"
  DASHBOARD_PASSWORD="${DASHBOARD_PASSWORD:-$(rand_hex 12)}"
  S3_PROTOCOL_ACCESS_KEY_ID="${S3_PROTOCOL_ACCESS_KEY_ID:-$(rand_hex 16)}"
  S3_PROTOCOL_ACCESS_KEY_SECRET="${S3_PROTOCOL_ACCESS_KEY_SECRET:-$(rand_hex 32)}"
  DASHBOARD_USERNAME="${DASHBOARD_USERNAME:-supabase}"

  # ANON_KEY / SERVICE_ROLE_KEY must be HS256 JWTs signed with JWT_SECRET.
  now=$(date +%s)
  exp=$((now + 10 * 365 * 24 * 3600))
  gen_key() {
    node -e '
      const crypto = require("node:crypto");
      const [secret, role, iat, exp] = process.argv.slice(1);
      const b64u = (o) => Buffer.from(JSON.stringify(o)).toString("base64url");
      const h = b64u({ alg: "HS256", typ: "JWT" });
      const p = b64u({ role, iss: "supabase", iat: +iat, exp: +exp });
      const s = crypto.createHmac("sha256", secret).update(h + "." + p).digest("base64url");
      process.stdout.write(h + "." + p + "." + s);
    ' "$JWT_SECRET" "$1" "$now" "$exp"
  }
  ANON_KEY="$(gen_key anon)"
  SERVICE_ROLE_KEY="$(gen_key service_role)"

  {
    cat docker/supabase/.env.example
    # Append overrides at the end (later assignments win in compose .env).
    cat <<EOF

# --- generated by scripts/setup-docker.sh on $(date +%Y-%m-%d) ---
POSTGRES_PASSWORD=$POSTGRES_PASSWORD
JWT_SECRET=$JWT_SECRET
ANON_KEY=$ANON_KEY
SERVICE_ROLE_KEY=$SERVICE_ROLE_KEY
DASHBOARD_USERNAME=$DASHBOARD_USERNAME
DASHBOARD_PASSWORD=$DASHBOARD_PASSWORD
SECRET_KEY_BASE=$SECRET_KEY_BASE
VAULT_ENC_KEY=$VAULT_ENC_KEY
PG_META_CRYPTO_KEY=$PG_META_CRYPTO_KEY
S3_PROTOCOL_ACCESS_KEY_ID=$S3_PROTOCOL_ACCESS_KEY_ID
S3_PROTOCOL_ACCESS_KEY_SECRET=$S3_PROTOCOL_ACCESS_KEY_SECRET
KONG_HTTP_PORT=$KONG_HTTP_PORT
KONG_HTTPS_PORT=${KONG_HTTPS_PORT:-8443}
POSTGRES_PORT=${POSTGRES_PORT:-5432}
POOLER_PROXY_PORT_TRANSACTION=${POOLER_PROXY_PORT_TRANSACTION:-6543}
SUPABASE_PUBLIC_URL=http://localhost:$KONG_HTTP_PORT
API_EXTERNAL_URL=http://localhost:$KONG_HTTP_PORT/auth/v1
SITE_URL=http://localhost:$WEB_PORT
EOF
  } > "$SBU_ENV"
  ok "wrote $SBU_ENV"
fi

# Keep BARRY_* in sync: root .env is the single place the user configures
# the LLM endpoint; the edge function reads them from docker/supabase/.env.
if [ -f "$ROOT_ENV" ]; then
  root_val() { grep -E "^$1=" "$ROOT_ENV" 2>/dev/null | head -1 | cut -d= -f2- | tr -d '"'; }
  for k in BARRY_BASE_URL BARRY_API_KEY BARRY_MODEL BARRY_EMBEDDING_MODEL; do
    v=$(root_val "$k")
    if [ -n "$v" ]; then
      if grep -qE "^$k=" "$SBU_ENV"; then
        tmp=$(mktemp); sed "s|^$k=.*|$k=$v|" "$SBU_ENV" > "$tmp" && mv "$tmp" "$SBU_ENV"
      else
        printf '%s=%s\n' "$k" "$v" >> "$SBU_ENV"
      fi
    fi
  done
fi

# --------------------------------------------------------------------------
# 2. Root .env (client config, baked into the web image at build time)
# --------------------------------------------------------------------------
if [ ! -f "$ROOT_ENV" ]; then
  info "generating root .env"
  cp .env.example "$ROOT_ENV"
fi
read_sbu() { grep -E "^$1=" "$SBU_ENV" | tail -1 | cut -d= -f2-; }
LOCAL_ANON_KEY=$(read_sbu ANON_KEY)

set_root_var() { # key value — fill in only if currently empty
  local key=$1 val=$2 cur tmp
  cur=$(grep -E "^$key=" "$ROOT_ENV" 2>/dev/null | head -1 | cut -d= -f2- || true)
  if [ -n "$cur" ]; then
    return 0 # user-provided value wins
  fi
  if grep -qE "^$key=" "$ROOT_ENV" 2>/dev/null; then
    # exists but empty → fill in place (no duplicate lines)
    tmp=$(mktemp); sed "s|^$key=.*|$key=$val|" "$ROOT_ENV" > "$tmp" && mv "$tmp" "$ROOT_ENV"
  else
    printf '%s=%s\n' "$key" "$val" >> "$ROOT_ENV"
  fi
  ok "set $key in .env"
}
set_root_var VITE_SUPABASE_URL "http://localhost:$KONG_HTTP_PORT"
set_root_var VITE_SUPABASE_ANON_KEY "$LOCAL_ANON_KEY"
set_root_var WEB_PORT "$WEB_PORT"

cur_url=$(grep -E '^VITE_SUPABASE_URL=' "$ROOT_ENV" | head -1 | cut -d= -f2-)
if [ -n "$cur_url" ] && [ "$cur_url" != "http://localhost:$KONG_HTTP_PORT" ]; then
  echo "  note: .env points at $cur_url (not the local stack) — is that intentional?"
fi

# --------------------------------------------------------------------------
# 3. Sync edge functions
# --------------------------------------------------------------------------
info "syncing edge functions"
scripts/sync-functions.sh

# --------------------------------------------------------------------------
# 4. Build + start
# --------------------------------------------------------------------------
info "docker compose up -d --build (first run pulls images + builds the web app)"
docker compose up -d --build

# --------------------------------------------------------------------------
# 5. Wait for health
# --------------------------------------------------------------------------
info "waiting for the stack to become healthy"

wait_container() { # container label [max-seconds]
  local c=$1 label=$2 max=${3:-240} i status
  for i in $(seq 1 $((max / 3))); do
    status=$(docker inspect --format \
      '{{if .State.Health}}{{.State.Health.Status}}{{else}}{{.State.Status}}{{end}}' \
      "$c" 2>/dev/null || echo missing)
    case "$status" in
      healthy|running) return 0 ;;
      missing) ;; # not started yet — keep waiting
      *)
        echo "  $label is $status" >&2
        docker compose logs --tail 25 "$c" >&2 || true
        fail "$label did not start"
        ;;
    esac
    sleep 3
  done
  fail "timed out waiting for $label (last status: $status)"
}

wait_url() { # url label
  local url=$1 label=$2 i
  for i in $(seq 1 60); do
    if curl -sf -o /dev/null "$url"; then
      ok "$label is up"
      return 0
    fi
    sleep 2
  done
  fail "timed out waiting for $label ($url)"
}

wait_container supabase-db "Postgres" 180 && ok "Postgres is up"
wait_container supabase-kong "API gateway (kong)" 240 && ok "kong is up"
wait_url "http://localhost:$KONG_HTTP_PORT/auth/v1/health" "Auth"
wait_container supabase-edge-functions "Edge functions" 180
wait_url "http://localhost:$KONG_HTTP_PORT/functions/v1/hello" "Edge runtime (hello function)"
wait_container babyapp-web "Web app" 300
wait_url "http://localhost:$WEB_PORT/" "Web app HTTP"

# --------------------------------------------------------------------------
# 6. Migrations
# --------------------------------------------------------------------------
info "applying database migrations"
scripts/apply-migrations.sh

# --------------------------------------------------------------------------
# Done
# --------------------------------------------------------------------------
DASH_USER=$(read_sbu DASHBOARD_USERNAME)
info "all set"
cat <<EOF
  App:        http://localhost:$WEB_PORT   (installable PWA)
  Studio:     http://localhost:$KONG_HTTP_PORT/studio   ($DASH_USER / see docker/supabase/.env → DASHBOARD_PASSWORD)
  API:        http://localhost:$KONG_HTTP_PORT
  Postgres:   localhost:${POSTGRES_PORT:-5432}  (user: postgres)
  Barry:      configured when BARRY_BASE_URL + BARRY_API_KEY are set in .env
              (then: scripts/sync-functions.sh is not needed — restart the
              functions service: docker compose up -d functions)

  Useful commands:
    make logs      tail logs
    make ps        service status
    make migrate   re-apply migrations (idempotent)
    make down      stop everything (data is kept)
    make reset     stop + destroy all local data

  Barry is optional: without BARRY_* secrets the app runs fully offline
  and Barry shows an "offline" notice in the chat.
EOF
